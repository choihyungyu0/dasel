// v6 기능 캡처(1600×900). 실행: node scripts/check_v6.mjs [주소]
import { mkdirSync } from "node:fs";
import { chromium } from "playwright-core";
const BASE = process.argv[2] ?? "https://dasel-weld.vercel.app";
mkdirSync("screenshots/poster", { recursive: true });
const browser = await chromium.launch({ channel: "chrome", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const ctx = await browser.newContext({ viewport: { width: 1600, height: 900 }, locale: "ko-KR" });
await ctx.addInitScript(() => { try { localStorage.setItem("dasel_tour_v1", "done"); } catch {} });
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(String(e).slice(0, 200)));
const out = {};
await page.goto(`${BASE}/?b=121902`);
await page.waitForSelector("#TXT-PANEL", { timeout: 60000 });
await page.waitForTimeout(6000);
out.panel = await page.locator("#TXT-PANEL").innerText();
out.panelFeatures = await page.evaluate(() => null);
await page.screenshot({ path: "screenshots/poster/pc_9_panels.png" });
await page.locator("#TAB-AI-BTN").click();
await page.waitForSelector("#TAB-AI");
await page.waitForTimeout(2500);
out.evidence = (await page.locator("#TAB-AI").innerText()).replace(/\s+/g, " ").slice(0, 300);
await page.screenshot({ path: "screenshots/poster/pc_11_evidence.png" });
await page.goto(`${BASE}/list`);
await page.waitForSelector("#INP-NL");
await page.waitForTimeout(2000);
await page.fill("#INP-NL", "오창과학 200kW 이상 내진설계 적용 공장");
await page.click("#BTN-NL");
await page.waitForSelector("#NL-CHIPS", { timeout: 15000 }).catch(() => {});
await page.waitForTimeout(1500);
out.chips = await page.locator("#NL-CHIPS").innerText().catch(() => "없음");
out.rows = await page.locator("tbody tr").count();
await page.screenshot({ path: "screenshots/poster/pc_12_nl_chips.png" });
out.errs = errs;
console.log(JSON.stringify(out, null, 1));
await browser.close();
